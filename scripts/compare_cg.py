"""Baseline vs clock-gated comparison, read only from evidence files.

Writes reports/cg/comparison.json and reports/cg/comparison.md. Any item whose
evidence file is missing is reported as "pending", never estimated.
Power columns use reports/power_<variant>/ (activity simulated on each
variant's final netlist, see scripts/activity_power_variant.sh).
"""
from pathlib import Path
import json, re

root = Path(__file__).resolve().parents[1]
PH = 'physical/{kind}/sky130hd/ecg_snn_core/{v}'


def load_json(p):
    p = root / p
    return json.loads(p.read_text()) if p.exists() else None


def vcd_end_s(p):
    p = root / p
    if not p.exists():
        return None
    with p.open('rb') as f:
        f.seek(max(0, p.stat().st_size - 4096))
        return int(re.findall(r'^#(\d+)', f.read().decode(errors='replace'), re.M)[-1]) * 1e-12


def text(p):
    p = root / p
    return p.read_text(errors='replace') if p.exists() else ''


def variant(v):
    rep = load_json(PH.format(kind='logs', v=v) + '/6_report.json') or {}
    drc = text(PH.format(kind='reports', v=v) + '/6_drc_count.rpt').strip()
    lvs = text(PH.format(kind='logs', v=v) + '/6_lvs.log')
    route = text(PH.format(kind='logs', v=v) + '/5_2_route.log')
    ant = re.findall(r'ANT-0002\] Found (\d+) net violations', route)
    pw = {k: load_json(f'reports/power_{v}/{k}.json') for k in ('activity', 'idle')}
    t_act = vcd_end_s(f'reports/power_{v}/activity.vcd')
    cov = re.findall(r'^unannotated\s+(\d+)', text(f'reports/power_{v}/activity_coverage.rpt'), re.M)
    d = {
        'setup_ws_ns': rep.get('finish__timing__setup__ws'),
        'hold_ws_ns': rep.get('finish__timing__hold__ws'),
        'setup_tns_ns': rep.get('finish__timing__setup__tns'),
        'hold_tns_ns': rep.get('finish__timing__hold__tns'),
        'stdcell_area_um2': rep.get('finish__design__instance__area__stdcell'),
        'stdcell_count': rep.get('finish__design__instance__count__stdcell'),
        'utilization': rep.get('finish__design__instance__utilization'),
        'clock_buffers': rep.get('finish__design__instance__count__class:clock_buffer'),
        'drc_violations': int(drc) if drc.isdigit() else None,
        'lvs': ('match' if 'Netlists match' in lvs else 'not matched') if lvs else None,
        'antenna_net_violations': int(ant[-1]) if ant else None,
        'activity_unannotated_pins': int(cov[0]) if cov else None,
        'activity_window_us': t_act * 1e6 if t_act else None,
        'activity_power_mW': pw['activity']['Total']['total'] * 1e3 if pw['activity'] else None,
        'idle_power_mW': pw['idle']['Total']['total'] * 1e3 if pw['idle'] else None,
        'idle_clock_group_mW': pw['idle']['Clock']['total'] * 1e3 if pw['idle'] else None,
        'leakage_nW': pw['activity']['Total']['leakage'] * 1e9 if pw['activity'] else None,
    }
    if d['activity_power_mW'] is not None and t_act:
        d['window_energy_uJ'] = d['activity_power_mW'] * 1e-3 * t_act * 1e6
    if d['idle_power_mW'] is not None:
        # Clock-on idle cost of one second with no beat to process.
        d['idle_energy_per_s_uJ'] = d['idle_power_mW'] * 1e3
    fg = text('reports/cg/final_gate_simulation.log' if v == 'cg' else 'reports/final_gate_simulation.log')
    d['final_netlist_500_vectors'] = 'PASS' if 'PASS vectors=500 mismatches=0' in fg else None
    return d


res = {'base': variant('base'), 'cg': variant('cg')}
keys = list(res['base'].keys() | res['cg'].keys())
order = [k for k in ['final_netlist_500_vectors', 'setup_ws_ns', 'setup_tns_ns', 'hold_ws_ns', 'hold_tns_ns',
                     'stdcell_count', 'stdcell_area_um2', 'utilization', 'clock_buffers', 'drc_violations',
                     'lvs', 'antenna_net_violations', 'activity_unannotated_pins', 'activity_window_us',
                     'activity_power_mW', 'window_energy_uJ', 'idle_power_mW', 'idle_clock_group_mW',
                     'idle_energy_per_s_uJ', 'leakage_nW'] if k in keys]


def fmt(x):
    if x is None:
        return 'pending'
    if isinstance(x, float):
        return f'{x:.6g}'
    return str(x)


rows = ['| Metric | Baseline (base) | Clock-gated (cg) | cg / base |', '|---|---|---|---|']
for k in order:
    a, b = res['base'].get(k), res['cg'].get(k)
    ratio = f'{b / a:.4g}' if isinstance(a, (int, float)) and isinstance(b, (int, float)) and a and not isinstance(a, bool) else ''
    rows.append(f'| {k} | {fmt(a)} | {fmt(b)} | {ratio} |')
out = root / 'reports/cg'
out.mkdir(parents=True, exist_ok=True)
(out / 'comparison.json').write_text(json.dumps(res, indent=2) + '\n')
(out / 'comparison.md').write_text(
    '# Baseline vs clock-gated variant\n\nGenerated by scripts/compare_cg.py from evidence files; '
    '"pending" means the evidence file does not exist yet.\nPower: OpenSTA estimate, TT 25 C 1.8 V, '
    'extracted RC, activity from zero-delay simulation of each final netlist.\n\n' + '\n'.join(rows) + '\n')
print('\n'.join(rows))
