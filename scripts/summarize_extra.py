"""Summarize reports/signoff_extra/ (corner STA, FEOL DRC, frequency sweep).

Writes summary.json and summary.md in the same folder. Missing inputs are
reported as "missing"; nothing is estimated.
"""
from pathlib import Path
import json, re, collections
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
O = root / 'reports/signoff_extra'
T_WINDOW = 628.861e-6   # s, 20-vector window at 25 MHz
CORNERS = ['tt_025C_1v80', 'ff_n40C_1v95', 'ss_100C_1v60']
VARIANTS = ['base', 'cg']


def num(pat, s):
    m = re.search(pat, s, re.M)
    return float(m.group(1)) if m else None


def sec_count(v, name):
    if name not in v:
        return 0
    part = v.split(name, 1)[1]
    part = re.split(r'\n(?:max slew|max capacitance|max fanout)\n', part)[0]
    return part.count('VIOLATED')


def sta(v, c):
    p = O / f'sta_{v}_{c}.rpt'
    if not p.exists():
        return 'missing'
    s = p.read_text(errors='replace')
    viol = s.split('### violators', 1)[-1].split('### end violators', 1)[0]
    hold = s.split('### worst hold paths', 1)[-1]
    ep = re.search(r'Endpoint: (\S+)', hold)
    return {
        'setup_wns_ns': num(r'^worst slack max (\S+)', s),
        'hold_wns_ns': num(r'^worst slack min (\S+)', s),
        'setup_tns_ns': num(r'^tns max (\S+)', s),
        'hold_or_setup_violating_endpoints': len([x for x in re.findall(r'^core_clk\s+(-?[\d.]+)', viol, re.M) if float(x) < 0]),
        'hold_or_setup_tns_ns': sum(float(x) for x in re.findall(r'^core_clk\s+(-?[\d.]+)', viol, re.M) if float(x) < 0),
        'max_slew_violations': sec_count(viol, 'max slew'),
        'max_cap_violations': sec_count(viol, 'max capacitance'),
        'worst_hold_endpoint': ep.group(1) if ep else None,
        'errors': len(re.findall(r'^\[ERROR', s, re.M)),
    }


def drc(v):
    p = O / f'drc_mr_{v}.lyrdb'
    if not p.exists():
        return 'missing'
    cats = collections.Counter()
    items = ET.parse(p).getroot().find('items')
    for item in (list(items) if items is not None else []):
        c = item.find('category')
        cats[(c.text or '').strip("'") if c is not None else '?'] += 1
    log = (O / f'drc_mr_{v}.log').read_text(errors='replace') if (O / f'drc_mr_{v}.log').exists() else ''
    return {'items': sum(cats.values()), 'by_rule': dict(cats.most_common()),
            'feol_enabled': 'FEOL section' in log, 'exit': (re.findall(r'klayout exit status (\d+)', log) or ['?'])[-1]}


def power(v, f):
    d = O / f'power_{v}_{f}MHz'
    try:
        a = json.loads((d / 'activity.json').read_text())['Total']
        i = json.loads((d / 'idle.json').read_text())['Total']
        k = float((d / 'time_scale.txt').read_text())
    except (FileNotFoundError, json.JSONDecodeError, ValueError):
        return 'missing'
    t = T_WINDOW * k
    e_win = a['total'] * t
    e_inc = (a['total'] - i['total']) * t
    return {'clock_MHz': f, 'window_s': t,
            'window_power_mW': a['total'] * 1e3, 'window_energy_uJ': e_win * 1e6,
            'idle_power_uW': i['total'] * 1e6, 'leakage_nW': i['leakage'] * 1e9,
            'incremental_energy_per_vector_nJ': e_inc / 20 * 1e9,
            'avg_power_at_1_beat_per_s_uW': (i['total'] + e_inc / 20) * 1e6}


res = {'sta': {v: {c: sta(v, c) for c in CORNERS} for v in VARIANTS},
       'drc_feol': {v: drc(v) for v in VARIANTS},
       'power_sweep': {v: {f: power(v, f) for f in [25, 10, 5, 1]} for v in VARIANTS}}
lib = O / 'corner_libs.txt'
res['corner_libs'] = lib.read_text() if lib.exists() else 'missing'
(O / 'summary.json').write_text(json.dumps(res, indent=2) + '\n')

g = lambda x, fmt='{:.4g}': 'missing' if x is None else fmt.format(x)
md = ['# Extra checks: corner STA, FEOL DRC, clock-frequency power sweep', '',
      'Generated by scripts/summarize_extra.py from reports/signoff_extra/.', '',
      '## Library-corner STA (40 ns, extracted nominal RC)', '',
      '| Variant | Corner | Setup WNS (ns) | Hold WNS (ns) | Violating endpoints | Total negative slack (ns) | Max slew / cap violations | Worst hold endpoint |',
      '|---|---|---|---|---|---|---|---|']
for v in VARIANTS:
    for c in CORNERS:
        r = res['sta'][v][c]
        if r == 'missing':
            md.append(f'| {v} | {c} | missing | | | | | |'); continue
        md.append(f"| {v} | {c} | {g(r['setup_wns_ns'])} | {g(r['hold_wns_ns'])} | {r['hold_or_setup_violating_endpoints']} | "
                  f"{r['hold_or_setup_tns_ns']:.3f} | {r['max_slew_violations']} / {r['max_cap_violations']} | `{r['worst_hold_endpoint']}` |")
md += ['', '## Full-chip DRC, open_pdks sky130A_mr.drc (FEOL + BEOL + off-grid)', '', '| Variant | Items | Top rules |', '|---|---|---|']
for v in VARIANTS:
    r = res['drc_feol'][v]
    if r == 'missing':
        md.append(f'| {v} | missing | |'); continue
    top = ', '.join(f'{k}: {n}' for k, n in list(r['by_rule'].items())[:6]) or '—'
    md.append(f"| {v} | {r['items']}{'' if r['feol_enabled'] else ' (FEOL flag not confirmed)'} | {top} |")
md += ['', '## Power vs clock frequency (OpenSTA, TT, time-stretched zero-delay activity)', '',
       '| Variant | Clock | Window power | Window energy (20 vectors) | Idle power | Incremental energy / vector | Avg power at 1 beat/s |',
       '|---|---|---|---|---|---|---|']
for v in VARIANTS:
    for f in [25, 10, 5, 1]:
        r = res['power_sweep'][v][f]
        if r == 'missing':
            md.append(f'| {v} | {f} MHz | missing | | | | |'); continue
        md.append(f"| {v} | {f} MHz | {r['window_power_mW']:.4g} mW | {r['window_energy_uJ']:.4g} µJ | "
                  f"{r['idle_power_uW']:.4g} µW | {r['incremental_energy_per_vector_nJ']:.4g} nJ | "
                  f"{r['avg_power_at_1_beat_per_s_uW']:.4g} µW |")
md += ['', 'Consistency: the 25 MHz sweep point must equal reports/power_<variant>/ (same activity, same period).', '']
for v in VARIANTS:
    ref = root / f'reports/power_{v}/activity.json'
    r = res['power_sweep'][v][25]
    if ref.exists() and r != 'missing':
        p0 = json.loads(ref.read_text())['Total']['total'] * 1e3
        md.append(f"- {v}: sweep {r['window_power_mW']:.6g} mW vs original {p0:.6g} mW")
(O / 'summary.md').write_text('\n'.join(md) + '\n')
print('\n'.join(md))
